// Copies the API's Zod contracts (source of truth, ADR 0002 in the API repo) into src/contracts.
// Usage: npm run contracts:sync [-- <path-to-api-repo>]   (default: ../mahatechz-solutions-Api)
import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const apiRepo = resolve(process.argv[2] ?? "../mahatechz-solutions-Api");
const from = join(apiRepo, "src", "contracts");
const to = resolve("src", "contracts");
mkdirSync(to, { recursive: true });

const files = readdirSync(from).filter((f) => f.endsWith(".ts"));
for (const file of files) {
  copyFileSync(join(from, file), join(to, file));
  // The API uses NodeNext ".js" import specifiers; Metro resolves extensionless imports.
  const path = join(to, file);
  writeFileSync(path, `// GENERATED by scripts/sync-contracts.mjs from the API repo — do not edit.\n${readFileSync(path, "utf8").replace(/from "(\.\/[^"]+)\.js"/g, 'from "$1"')}`);
}
console.log(`Synced ${files.length} contract files from ${from}`);
